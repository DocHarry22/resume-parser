const { chromium, browserChannel, baseUrl } = require('../../scripts/playwright-runtime.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname);
const result = { startedAt: new Date().toISOString(), checks: [], browserErrors: [] };
const note = message => { result.checks.push(message); console.log(message); };
let browser, page;
(async () => {
  browser = await chromium.launch({ channel: browserChannel, headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page = await context.newPage();
  page.setDefaultTimeout(20000); page.setDefaultNavigationTimeout(120000);
  page.on('pageerror', error => { result.browserErrors.push(error.message); console.log('PAGE ERROR: ' + error.message); });
  page.on('console', message => { if(message.type()==='error') { result.browserErrors.push(message.text()); console.log('CONSOLE ERROR: '+message.text()); } });
  const go = async route => { await page.goto(baseUrl + route, { waitUntil: 'domcontentloaded' }); await page.locator('main').waitFor(); if(['/job-tracker','/dashboard'].includes(route)) await page.locator('main[data-workspace-ready=true]').waitFor(); if(route==='/cover-letter') await page.locator('main[data-letter-ready=true]').waitFor(); await page.evaluate(()=>scrollTo(0,0)); };
  const screenshot = async name => { await page.evaluate(()=>scrollTo(0,0)); return page.screenshot({ path: path.join(root, name + '.png'), fullPage: true }); };
  const noOverflow = async label => { const size = await page.evaluate(() => ({ width: innerWidth, documentWidth: document.documentElement.scrollWidth })); assert.ok(size.documentWidth <= size.width + 1, `${label} horizontal overflow ${JSON.stringify(size)}`); note(label + ': no horizontal overflow'); };
  await go('/job-tracker');
  console.log('Starting job tracker actions');
  await page.getByRole('button', { name: 'Add a job', exact: true }).click();
  await page.getByLabel('Job title', { exact: true }).fill('Platform engineer QA');
  await page.getByLabel('Company', { exact: true }).fill('Evidence Company');
  await page.getByLabel('Job listing URL').fill('https://example.com/jobs/platform');
  await page.getByLabel('Application date').fill('2026-10-12');
  await page.getByLabel('Follow-up date').fill('2026-10-14');
  await page.getByLabel('Notes', { exact: true }).fill('Follow up with the recruiter. Unicode: Zoë.');
  await page.getByRole('button', { name: 'Save job', exact: true }).click();
  await page.getByRole('heading', { name: 'Platform engineer QA', exact: true }).waitFor();
  await page.getByRole('combobox', { name: 'Stage for Platform engineer QA at Evidence Company' }).selectOption('Interview');
  await page.reload({ waitUntil: 'domcontentloaded' });
  assert.equal(await page.getByRole('combobox', { name: 'Stage for Platform engineer QA at Evidence Company' }).inputValue(), 'Interview');
  await page.getByRole('button', { name: 'Edit details', exact: true }).click();
  await page.getByLabel('Job title', { exact: true }).fill('Senior platform engineer QA');
  await page.getByRole('button', { name: 'Save job', exact: true }).click();
  await page.getByRole('heading', { name: 'Senior platform engineer QA', exact: true }).waitFor();
  const backupEvent = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export backup' }).click();
  const backup = await backupEvent; const backupPath = path.join(root, 'job-backup.json'); await backup.saveAs(backupPath);
  assert.equal(JSON.parse(fs.readFileSync(backupPath, 'utf8')).jobs[0].role, 'Senior platform engineer QA');
  await page.getByLabel('Search jobs').fill('missing role');
  await page.getByRole('heading', { name: 'No matching opportunities' }).waitFor();
  await page.getByLabel('Search jobs').fill('');
  note('Job tracker: add, edit, stage change, reload persistence, search and JSON export passed');
  for (const [width, height, name] of [[1440,1000,'desktop'],[820,1180,'tablet'],[390,844,'mobile']]) {
    await page.setViewportSize({width,height}); await noOverflow('Job tracker '+name); await screenshot('job-tracker-'+name);
    await page.getByRole('button', { name: 'Add a job', exact: true }).click(); await noOverflow('Job modal '+name); await screenshot('job-dialog-'+name); await page.getByRole('button', {name:'Close job form'}).click();
    await go('/dashboard'); await page.getByRole('heading', {name:'Make your next move.'}).waitFor(); await noOverflow('Dashboard '+name); await screenshot('dashboard-'+name);
    await go('/job-tracker');
  }
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button', {name:'Delete',exact:true}).click();
  await page.getByRole('heading', {name:'Your next opportunity starts here'}).waitFor();
  await page.getByLabel('Import job tracker backup').setInputFiles(backupPath);
  await page.getByRole('heading', {name:'Senior platform engineer QA',exact:true}).waitFor();
  note('Job tracker: delete and backup restore passed');
  await page.setViewportSize({width:1440,height:1000});
  await go('/cover-letter');
  await page.getByRole('button', {name:'Create cover letter',exact:true}).click();
  await page.getByLabel('Cover letter title').fill('QA letter – platform engineer');
  await page.getByRole('button', {name:'Job Details',exact:true}).click();
  await page.getByLabel('job title',{exact:true}).fill('Platform Engineer');
  await page.getByLabel('company name',{exact:true}).fill('Evidence Company');
  await page.getByRole('button', {name:'Your Information',exact:true}).click();
  await page.getByLabel('full name',{exact:true}).fill('Zoë Naïdø');
  await page.getByLabel('email',{exact:true}).fill('qa@example.com');
  await page.getByRole('button', {name:'Write Content',exact:true}).click();
  await page.getByLabel('Opening paragraph').fill('I am applying for the Platform Engineer role. I enjoy building thoughtful tools.');
  await page.getByRole('button', {name:'📝 Body',exact:true}).click();
  await page.getByLabel('Body paragraph 1').fill('I built a reporting workflow for my team, improving the visibility of daily work.');
  await page.getByRole('button', {name:'🎯 Closing',exact:true}).click();
  await page.getByLabel('Closing paragraph').fill('I would welcome a conversation about the role. Thank you for considering my application.');
  await page.getByRole('button', {name:'Save',exact:true}).click();
  await page.getByText('Cover letter saved.',{exact:true}).waitFor({timeout:60000});
  await page.getByLabel('Cover letter title').fill('QA letter – updated');
  await page.getByRole('button', {name:'Save',exact:true}).click();
  await page.waitForTimeout(1500);
  await page.getByRole('button',{name:'All cover letters',exact:false}).click();
  await page.getByRole('heading',{name:'QA letter – updated',exact:true}).waitFor();
  assert.equal(await page.locator('article').count(),1, 'Repeated save must update rather than duplicate');
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:'QA letter – updated',exact:true}).waitFor();
  await page.getByRole('button',{name:'Edit letter',exact:true}).click();
  await page.getByRole('button',{name:'Write Content',exact:true}).click();
  assert.match(await page.getByLabel('Opening paragraph').inputValue(), /thoughtful tools/);
  await page.getByLabel('Opening paragraph').fill('UNSAVED EXPORT MARKER. Zoë Naïdø is applying for the Platform Engineer role.');
  for (const format of ['DOCX','PDF','TXT']) {
    const downloaded = page.waitForEvent('download',{timeout:60000});
    await page.getByRole('button',{name:'Export',exact:true}).click();
    await page.getByRole('button',{name:'Download '+format,exact:false}).click();
    const download = await downloaded; const file = path.join(root,'cover-current.'+format.toLowerCase()); await download.saveAs(file);
    const data = fs.readFileSync(file); assert.ok(data.length>50,format+' export must contain a document');
    if(format==='PDF') assert.equal(data.subarray(0,4).toString(),'%PDF');
    if(format==='DOCX') assert.equal(data.subarray(0,2).toString(),'PK');
    if(format==='TXT') assert.match(data.toString('utf8'), /UNSAVED EXPORT MARKER/);
    note('Cover letter '+format+': download passed ('+data.length+' bytes)');
  }
  for (const [width,height,name] of [[1440,1000,'desktop'],[820,1180,'tablet'],[390,844,'mobile']]) { await page.setViewportSize({width,height}); await noOverflow('Cover editor '+name); await screenshot('cover-editor-'+name); }
  await page.getByRole('button',{name:'All cover letters',exact:false}).click(); await page.getByRole('heading',{name:'QA letter – updated',exact:true}).waitFor();
  for (const [width,height,name] of [[1440,1000,'desktop'],[820,1180,'tablet'],[390,844,'mobile']]) { await page.setViewportSize({width,height}); await noOverflow('Cover list '+name); await screenshot('cover-list-'+name); }
  note('Cover letter: create/save/update without duplicates/reload/current unsaved export passed');
  result.finishedAt = new Date().toISOString(); result.passed = true;
  fs.writeFileSync(path.join(root,'career-e2e-results.json'),JSON.stringify(result,null,2));
  await browser.close();
})().catch(async error => { result.passed=false; result.failure=error.stack; if(page) { await page.screenshot({path:path.join(root,'career-e2e-failure.png'),fullPage:true}).catch(()=>{}); result.failurePage = await page.locator('body').innerText().catch(()=>''); } console.error(error); fs.writeFileSync(path.join(root,'career-e2e-results.json'),JSON.stringify(result,null,2)); if(browser) await browser.close(); process.exitCode=1; });
