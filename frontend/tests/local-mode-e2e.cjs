// Run only against a frontend built with NEXT_PUBLIC_STORAGE_MODE=local and a stateless backend.
const { chromium, browserChannel, baseUrl } = require('../../scripts/playwright-runtime.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const output = process.env.QA_OUTPUT ? path.resolve(process.env.QA_OUTPUT) : path.resolve(__dirname, '../../docs/qa/local-mode');
fs.mkdirSync(output, { recursive: true });
const report = { startedAt: new Date().toISOString(), baseUrl, checks: [], apiRequests: [], pageErrors: [] };
const note = value => { report.checks.push(value); console.log(value); };
let browser;
(async () => {
  browser = await chromium.launch({ channel: browserChannel, headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const page = await context.newPage();
  page.setDefaultTimeout(25000); page.setDefaultNavigationTimeout(120000);
  page.on('pageerror', error => report.pageErrors.push(error.message));
  page.on('request', request => { const url = new URL(request.url()); if (url.pathname.startsWith('/api/')) report.apiRequests.push({ path: url.pathname, method: request.method() }); });
  const go = route => page.goto(baseUrl + route, { waitUntil: 'networkidle' });
  const download = async (name, action) => { const [file] = await Promise.all([page.waitForEvent('download'), action()]); const destination = path.join(output, name); await file.saveAs(destination); assert.ok(fs.statSync(destination).size > 20); return destination; };
  const exportLetter = async format => { await page.getByRole('button', { name: 'Export', exact: true }).click(); return download(`letter-current.${format}`, () => page.getByRole('button', { name: new RegExp(`Download ${format.toUpperCase()}$`) }).click()); };
  const noOverflow = async name => { const size = await page.evaluate(() => ({ width: innerWidth, content: document.documentElement.scrollWidth })); assert.ok(size.content <= size.width + 1, `${name}: overflow ${JSON.stringify(size)}`); };
  await go('/builder?new=1');
  await page.getByLabel('Resume title', { exact: true }).waitFor();
  assert.equal(await page.getByLabel(/^Full Name/).inputValue(), '');
  assert.equal(await page.getByRole('button', { name: 'Save session copy', exact: true }).count(), 0);
  await page.getByText('Saved only in this browser on this device.', { exact: false }).waitFor();
  await page.getByLabel('Resume title', { exact: true }).fill('Local QA resume');
  await page.getByLabel(/^Full Name/).fill('Local QA Zoë');
  await page.getByLabel(/^Email/).fill('local-qa@example.test');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByLabel(/^Full Name/).inputValue(), 'Local QA Zoë');
  await page.getByLabel(/^Full Name/).fill('CURRENT UNSAVED EXPORT');
  for (const format of ['pdf', 'docx']) {
    const [request] = await Promise.all([page.waitForRequest(req => new URL(req.url()).pathname === `/api/exports/resume/${format}`),
      download(`resume-current.${format}`, () => page.getByRole('button', { name: format === 'pdf' ? 'Download PDF' : 'DOCX', exact: true }).click())]);
    assert.equal(request.postDataJSON().contact.full_name, 'CURRENT UNSAVED EXPORT');
  }
  let before = report.apiRequests.length;
  const txt = await download('resume-current.txt', () => page.getByRole('button', { name: 'TXT', exact: true }).click());
  assert.match(fs.readFileSync(txt, 'utf8'), /CURRENT UNSAVED EXPORT/);
  const backup = await download('resume-current.json', () => page.getByRole('button', { name: 'JSON backup', exact: true }).click());
  assert.equal(JSON.parse(fs.readFileSync(backup)).resume.contact.full_name, 'CURRENT UNSAVED EXPORT');
  assert.equal(report.apiRequests.length, before);
  assert.ok(await page.getByRole('button', { name: 'Print / Save PDF', exact: true }).isVisible());
  note('Resume starts blank, saves/reloads locally, exports current PDF/DOCX, and creates offline TXT/JSON backups');
  const importResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/exports/resume/import');
  await page.getByLabel('Import resume', { exact: true }).setInputFiles({ name: 'local-import.txt', mimeType: 'text/plain', buffer: Buffer.from('Imported Local Candidate\nlocal-import@example.test\n\nSUMMARY\nPractical experience making useful tools.\n\nSKILLS\nPython, communication') });
  const parsed = await (await importResponse).json();
  assert.equal(parsed.resume.id, null); assert.equal(parsed.server_persistence, false);
  await page.getByText('Resume imported into a new document.', { exact: false }).waitFor();
  assert.equal(await page.getByLabel(/^Full Name/).inputValue(), parsed.resume.contact.full_name);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByLabel(/^Full Name/).inputValue(), parsed.resume.contact.full_name);
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('resume_studio_documents_v1'))[0].resume.id), undefined);
  note('Import parses directly into a separate browser document, clears server identity, and survives reload');
  for (const width of [1440, 390]) { await page.setViewportSize({ width, height: width === 390 ? 844 : 1050 }); await noOverflow(`Resume ${width}`); await page.screenshot({ path: path.join(output, `resume-${width}.png`), fullPage: true }); }
  await page.setViewportSize({ width: 1440, height: 1050 });
  await go('/cover-letter'); await page.locator('main[data-letter-ready=true]').waitFor();
  await page.getByRole('button', { name: 'Create cover letter', exact: true }).click();
  await page.getByLabel('Cover letter title').fill('Local QA letter');
  await page.getByRole('button', { name: 'Your Information', exact: true }).click();
  await page.getByLabel('full name', { exact: true }).fill('Zoë Naïdø');
  await page.getByLabel('email', { exact: true }).fill('local-qa@example.test');
  await page.getByRole('button', { name: 'Write Content', exact: true }).click();
  await page.getByLabel('Opening paragraph').fill('Saved letter opening.');
  await page.getByRole('button', { name: 'Save in browser', exact: true }).click();
  await page.getByText('Cover letter saved only in this browser on this device.', { exact: true }).waitFor();
  const letterId = await page.evaluate(() => JSON.parse(localStorage.getItem('resume-studio.letters.v1'))[0].id);
  await page.getByLabel('Opening paragraph').fill('UNSAVED LETTER EXPORT SENTINEL');
  for (const format of ['pdf', 'docx']) {
    const [request] = await Promise.all([page.waitForRequest(req => new URL(req.url()).pathname === `/api/exports/cover-letter/${format}`), exportLetter(format)]);
    assert.equal(request.postDataJSON().content.opening_paragraph, 'UNSAVED LETTER EXPORT SENTINEL');
  }
  before = report.apiRequests.length;
  await exportLetter('txt'); assert.equal(report.apiRequests.length, before);
  await context.setOffline(true);
  await page.getByLabel('Cover letter title').fill('Offline local letter');
  await page.getByRole('button', { name: 'Save in browser', exact: true }).click();
  await page.getByRole('button', { name: '← All cover letters', exact: true }).click();
  await page.getByRole('heading', { name: 'Offline local letter', exact: true }).waitFor();
  await context.setOffline(false);
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('heading', { name: 'Offline local letter', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Duplicate Offline local letter', exact: true }).click();
  await page.getByRole('heading', { name: 'Offline local letter (copy)', exact: true }).waitFor();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete Offline local letter (copy)', exact: true }).click();
  await page.getByRole('heading', { name: 'Offline local letter (copy)', exact: true }).waitFor({ state: 'hidden' });
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('resume-studio.letters.v1')).length), 1);
  note('Cover letters save offline, reload, duplicate and delete locally; PDF/DOCX exports include unsaved content');
  await page.getByRole('button', { name: 'Edit Offline local letter', exact: true }).click();
  await page.getByRole('button', { name: 'Write Content', exact: true }).click();
  await page.route('**/api/exports/cover-letter/pdf', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"Controlled QA outage"}' }));
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  await page.getByRole('button', { name: /Download PDF$/ }).click();
  await page.getByRole('alert').filter({ hasText: 'Export failed' }).waitFor();
  assert.equal(await page.getByLabel('Opening paragraph').inputValue(), 'UNSAVED LETTER EXPORT SENTINEL');
  await exportLetter('txt');
  await page.unroute('**/api/exports/cover-letter/pdf');
  for (const width of [1440, 390]) { await page.setViewportSize({ width, height: width === 390 ? 844 : 1050 }); await noOverflow(`Letter ${width}`); await page.screenshot({ path: path.join(output, `letter-${width}.png`), fullPage: true }); }
  note('Controlled export outage leaves edits intact and TXT remains available; mobile/desktop layouts fit');
  const fresh = await browser.newContext(); const other = await fresh.newPage();
  await other.goto(baseUrl + '/cover-letter', { waitUntil: 'networkidle' });
  await other.getByRole('heading', { name: 'Give your application a voice.', exact: true }).waitFor();
  await fresh.close();
  note('A fresh browser profile has an empty letter library');
  await go('/tools/builder?template=modern');
  await page.waitForURL(url => url.pathname === '/builder');
  await page.getByLabel('Resume title', { exact: true }).waitFor();
  assert.equal(await page.locator('.resume-document').getAttribute('data-template'), 'modern');
  note('Legacy builder entry redirects to the browser editor with its template selection');
  await go('/privacy');
  assert.equal(await page.getByRole('button', { name: 'Download server workspace', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Delete server workspace', exact: true }).count(), 0);
  await page.evaluate(() => localStorage.setItem('unrelated-qa-setting', 'keep'));
  before = report.apiRequests.length;
  const privacy = await download('browser-data.json', () => page.getByRole('button', { name: 'Download browser data', exact: true }).click());
  const data = JSON.parse(fs.readFileSync(privacy, 'utf8'));
  assert.equal(data['resume-studio.letters.v1'][0].id, letterId);
  assert.ok(data.resume_studio_documents_v1.length >= 2);
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button', { name: 'Delete browser data', exact: true }).click();
  assert.equal(await page.evaluate(() => localStorage.getItem('resume-studio.letters.v1')), null);
  assert.equal(await page.evaluate(() => localStorage.getItem('resume_studio_documents_v1')), null);
  assert.equal(await page.evaluate(() => localStorage.getItem('unrelated-qa-setting')), 'keep');
  assert.equal(report.apiRequests.length, before);
  note('Privacy backup includes local letters; deletion removes only app data and exposes no server controls');
  assert.ok(report.apiRequests.every(request => request.path.startsWith('/api/exports/')), JSON.stringify(report.apiRequests));
  assert.equal((await context.cookies()).filter(cookie => cookie.name.includes('workspace')).length, 0);
  assert.deepEqual(report.pageErrors, []);
  note('All observed API calls are stateless processing; no workspace cookie, persisted routes, or page errors');
  report.passed = true;
})().catch(error => { report.passed = false; report.error = error.stack; console.error(error); process.exitCode = 1; }).finally(async () => {
  report.finishedAt = new Date().toISOString(); fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify(report, null, 2)); if (browser) await browser.close();
});
