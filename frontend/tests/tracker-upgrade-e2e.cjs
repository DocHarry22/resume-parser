const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const browserTemp = path.resolve(__dirname, '../../.runtime/tracker-browser');
fs.mkdirSync(browserTemp, { recursive: true });
process.env.TEMP = browserTemp;
process.env.TMP = browserTemp;
const { chromium, browserChannel } = require('../../scripts/playwright-runtime.cjs');
const baseUrl = (process.env.BASE_URL || 'http://127.0.0.1:3100').replace(/\/+$/, '');
const output = path.resolve(process.env.QA_OUTPUT || path.join(__dirname, '../../docs/qa/tracker-upgrade'));
fs.mkdirSync(output, { recursive: true });
const report = { baseUrl, startedAt: new Date().toISOString(), checks: [], pageErrors: [] };
const note = message => { report.checks.push(message); console.log(message); };
const key = 'resume-studio.jobs.v1';
const typeFile = path.resolve(__dirname, '../types/coverLetter.ts');
const mod = new Module(typeFile, module);
mod._compile(ts.transpileModule(fs.readFileSync(typeFile, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, typeFile);
let browser;
(async () => {
  browser = await chromium.launch({ channel: browserChannel, headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, acceptDownloads: true });
  const page = await context.newPage();
  page.setDefaultTimeout(20000); page.setDefaultNavigationTimeout(120000);
  page.on('pageerror', error => report.pageErrors.push(error.message));
  const go = () => page.goto(`${baseUrl}/job-tracker`, { waitUntil: 'networkidle' });
  const ready = () => page.locator('main[data-workspace-ready=true]').waitFor();
  const stored = () => page.evaluate(key => JSON.parse(localStorage.getItem(key) || '[]'), key);
  const download = async (filename, action) => { const [file] = await Promise.all([page.waitForEvent('download'), action()]); const target = path.join(output, filename); await file.saveAs(target); return target; };
  const overflow = async name => { const dimensions = await page.evaluate(() => ({ viewport: innerWidth, content: document.documentElement.scrollWidth })); assert.ok(dimensions.content <= dimensions.viewport + 1, `${name}: ${JSON.stringify(dimensions)}`); };
  await go(); await ready();
  const today = await page.evaluate(() => { const date = new Date(); return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`; });
  await page.evaluate(({ letter }) => {
    localStorage.setItem('resume_studio_documents_v1', JSON.stringify([{ id: 'tracker-resume', resume: { title: 'Engineering resume', contact: { full_name: 'Tracker QA', email: 'tracker@example.test' } }, template: 'modern' }]));
    localStorage.setItem('resume-studio.letters.v1', JSON.stringify([{ ...letter, id: 'tracker-letter', title: 'Engineering introduction' }]));
  }, { letter: mod.exports.defaultCoverLetter });
  await page.reload({ waitUntil: 'networkidle' }); await ready();
  await page.getByRole('button', { name: 'Add a job', exact: true }).click();
  const dialog = page.getByRole('dialog');
  assert.equal(await dialog.getByLabel('Job title', { exact: true }).evaluate(element => element === document.activeElement), true);
  await dialog.getByLabel('Job title', { exact: true }).fill('Chemical Engineer');
  await dialog.getByLabel('Company', { exact: true }).fill('Atlas Energy');
  await dialog.getByLabel('Location', { exact: true }).fill('Johannesburg · Hybrid');
  await dialog.getByLabel('Salary', { exact: true }).fill('R55,000 / month');
  await dialog.getByLabel('Job listing URL', { exact: true }).fill('https://example.test/jobs/chemical-engineer');
  await dialog.getByLabel('Follow-up date', { exact: true }).fill(today);
  await dialog.getByLabel('Linked resume', { exact: true }).selectOption('tracker-resume');
  await dialog.getByLabel('Linked cover letter', { exact: true }).selectOption('tracker-letter');
  await dialog.getByLabel('Job description', { exact: true }).fill('Process engineering, plant safety and continuous improvement.');
  await dialog.getByLabel('Notes', { exact: true }).fill('Contact the hiring team after submitting.');
  await dialog.getByRole('button', { name: 'Save job', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  let [job] = await stored();
  assert.equal(job.location, 'Johannesburg · Hybrid'); assert.equal(job.salary, 'R55,000 / month'); assert.equal(job.resumeId, 'tracker-resume'); assert.equal(job.letterId, 'tracker-letter'); assert.match(job.description, /plant safety/);
  const card = page.locator(`.tracker-card[data-job-id="${job.id}"]`);
  assert.equal(await card.getByRole('link', { name: 'Resume', exact: true }).getAttribute('href'), '/builder?id=tracker-resume');
  assert.match(await card.getByRole('link', { name: 'Open listing for Chemical Engineer' }).getAttribute('rel'), /noopener/);
  note('Create stores job description, location, salary, notes, due date and linked local documents; links open the right editor.');

  await page.getByRole('button', { name: 'List', exact: true }).click();
  await page.getByLabel('Stage for Chemical Engineer at Atlas Energy').selectOption('Applied');
  assert.equal((await stored())[0].appliedOn, today);
  await page.getByLabel('Stage for Chemical Engineer at Atlas Energy').selectOption('Interview');
  await page.reload({ waitUntil: 'networkidle' }); await ready();
  assert.equal((await stored())[0].stage, 'Interview');
  await page.locator(`.tracker-card[data-job-id="${job.id}"]`).dragTo(page.getByRole('region', { name: 'Offer applications', exact: true }), { sourcePosition: { x: 13, y: 12 }, targetPosition: { x: 70, y: 90 } });
  await page.waitForFunction(key => JSON.parse(localStorage.getItem(key))[0].stage === 'Offer', key);
  await page.getByLabel('Stage for Chemical Engineer at Atlas Energy').selectOption('Interview');
  note('List stage menus and board drag/drop persist transitions; first Applied transition records its date.');

  await page.getByRole('button', { name: 'Calendar', exact: true }).click();
  await page.getByRole('button', { name: `${today}, 1 follow-up`, exact: true }).click();
  await page.locator('.tracker-calendar-agenda').getByRole('button', { name: 'Mark done', exact: true }).click();
  assert.equal((await stored())[0].followUpOn, '');
  await page.locator('.tracker-calendar-agenda').getByText('No follow-ups scheduled.', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'List', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Chemical Engineer at Atlas Energy', exact: true }).click();
  await dialog.getByLabel('Follow-up date', { exact: true }).fill(today);
  await dialog.getByRole('button', { name: 'Save job', exact: true }).click();
  await page.getByRole('button', { name: 'Reschedule follow-up for Chemical Engineer at Atlas Energy by 7 days', exact: true }).click();
  const later = (await stored())[0].followUpOn;
  assert.ok(later > today);
  await page.getByRole('button', { name: 'Complete follow-up for Chemical Engineer at Atlas Energy', exact: true }).click();
  assert.equal((await stored())[0].followUpOn, '');
  note('Calendar and follow-up agenda complete reminders and reschedule them by seven days.');

  await page.getByRole('button', { name: 'Add a job', exact: true }).click();
  await dialog.getByLabel('Job title', { exact: true }).fill('Process Analyst');
  await dialog.getByLabel('Company', { exact: true }).fill('=SUM(1,1)');
  await dialog.getByRole('button', { name: 'Save job', exact: true }).click();
  await page.getByLabel('Search jobs', { exact: true }).fill('plant safety');
  await page.getByText('1 of 2 opportunities', { exact: true }).waitFor();
  await page.getByLabel('Search jobs', { exact: true }).fill('');
  await page.locator('.tracker-stage-filters').getByRole('button', { name: /^Interview/ }).click();
  await page.getByText('1 of 2 opportunities · Interview', { exact: true }).waitFor();
  await page.locator('.tracker-stage-filters').getByRole('button', { name: /^All/ }).click();
  const jsonFile = await download('tracker-backup.json', () => page.getByRole('button', { name: 'Export backup', exact: true }).click());
  const backup = JSON.parse(fs.readFileSync(jsonFile, 'utf8'));
  assert.equal(backup.jobs.length, 2); assert.equal(backup.jobs.find(item => item.id === job.id).resumeId, 'tracker-resume');
  const csvFile = await download('tracker-export.csv', () => page.getByRole('button', { name: 'CSV', exact: true }).click());
  assert.match(fs.readFileSync(csvFile, 'utf8'), /"'=SUM\(1,1\)"/);
  note('Description search, stage counts and filters work; JSON preserves metadata and CSV prevents spreadsheet formulas.');

  await page.evaluate(key => { localStorage.removeItem(key); window.dispatchEvent(new Event('storage')); }, key);
  await page.getByRole('heading', { name: 'Make your next move', exact: true }).waitFor();
  await page.getByLabel('Import job tracker backup', { exact: true }).setInputFiles(jsonFile);
  await page.getByText('2 of 2 opportunities', { exact: true }).waitFor();
  await page.getByLabel('Import job tracker backup', { exact: true }).setInputFiles(jsonFile);
  await page.getByRole('status').filter({ hasText: 'Imported 0 jobs' }).waitFor();
  assert.equal((await stored()).length, 2);
  const beforeInvalid = await page.evaluate(key => localStorage.getItem(key), key);
  await page.getByLabel('Import job tracker backup', { exact: true }).setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify([{ ...backup.jobs[0], appliedOn: '2026-02-30' }])) });
  await page.getByRole('alert').filter({ hasText: 'invalid date' }).waitFor();
  assert.equal(await page.evaluate(key => localStorage.getItem(key), key), beforeInvalid);
  note('Backup recovery round trips all metadata, keeps existing IDs, and rejects impossible dates without changing storage.');

  await page.evaluate(key => { localStorage.setItem(key, '{broken-json'); }, key);
  await page.reload({ waitUntil: 'networkidle' }); await ready();
  assert.equal(await page.getByRole('button', { name: 'Add a job', exact: true }).isDisabled(), true);
  assert.equal(await page.evaluate(key => localStorage.getItem(key), key), '{broken-json');
  page.once('dialog', dialog => dialog.accept());
  await page.getByLabel('Import job tracker backup', { exact: true }).setInputFiles(jsonFile);
  await page.getByText('2 of 2 opportunities', { exact: true }).waitFor();
  await page.evaluate(key => { window.__trackerSetItem = Storage.prototype.setItem; Storage.prototype.setItem = function(name, value) { if (name === key) throw new DOMException('Full', 'QuotaExceededError'); return window.__trackerSetItem.call(this, name, value); }; }, key);
  await page.getByRole('button', { name: 'Add a job', exact: true }).click();
  await dialog.getByLabel('Job title', { exact: true }).fill('Unsaved role');
  await dialog.getByLabel('Company', { exact: true }).fill('Storage test');
  await dialog.getByRole('button', { name: 'Save job', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: 'not been saved' }).waitFor();
  assert.equal((await stored()).length, 2); assert.equal(await dialog.isVisible(), true);
  await page.evaluate(() => { Storage.prototype.setItem = window.__trackerSetItem; delete window.__trackerSetItem; });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('button', { name: 'Add a job', exact: true }).evaluate(element => element === document.activeElement), true);
  note('Corrupt storage stays untouched until explicit backup recovery; quota failure retains the draft and Escape restores focus.');

  await page.getByRole('button', { name: 'Add a job', exact: true }).click();
  await dialog.getByLabel('Job title', { exact: true }).fill('Another opportunity');
  await dialog.getByLabel('Company', { exact: true }).fill('Concurrent test');
  await page.evaluate(key => { const jobs = JSON.parse(localStorage.getItem(key)); jobs[0].notes = 'A change from another tab'; jobs[0].updatedAt = '2026-10-19T23:59:59.000Z'; localStorage.setItem(key, JSON.stringify(jobs)); }, key);
  await dialog.getByRole('button', { name: 'Save job', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: 'changed in another tab' }).waitFor();
  assert.equal((await stored()).length, 2); assert.equal((await stored())[0].notes, 'A change from another tab');
  await page.keyboard.press('Escape');
  note('A concurrent tracker change is detected before save and preserved instead of being overwritten.');

  await page.reload({ waitUntil: 'networkidle' }); await ready();
  await overflow('desktop board'); await page.screenshot({ path: path.join(output, 'tracker-board-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  for (const view of ['Board', 'List', 'Calendar']) { await page.getByRole('button', { name: view, exact: true }).click(); await overflow(`mobile ${view}`); await page.screenshot({ path: path.join(output, `tracker-${view.toLowerCase()}-390.png`), fullPage: true }); }
  await page.getByRole('button', { name: 'List', exact: true }).click();
  await page.getByRole('button', { name: 'Edit Chemical Engineer at Atlas Energy', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await dialog.getByRole('button', { name: 'Delete job', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  assert.equal((await stored()).length, 1);
  assert.deepEqual(report.pageErrors, []);
  note('Desktop and 390 px board/list/calendar fit the viewport, delete preserves other jobs, and no browser errors occur.');
  report.finishedAt = new Date().toISOString();
})().catch(error => { report.error = error.stack; console.error(error); process.exitCode = 1; }).finally(async () => { fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify(report, null, 2)); await browser?.close(); });
